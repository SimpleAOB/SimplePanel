package deploy

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// Static sites: when a Git app has no Dockerfile (or the user picks
// "Static site"), SimplePanel generates a Dockerfile that optionally runs a
// build command in a builder image and serves the output with nginx.

const (
	// StaticServerImage serves the files. The stable tag is re-pulled on
	// every build, so rebuilding picks up nginx security updates.
	StaticServerImage = "nginx:stable-alpine"
	// DefaultStaticBuildImage runs the build command when one is set.
	DefaultStaticBuildImage = "node:22-alpine"
	// staticDockerfile is written into the build context.
	staticDockerfile = ".simplepanel.static.Dockerfile"
)

// BuildTypes are the accepted values for an app's build type.
var BuildTypes = []string{"auto", "dockerfile", "static"}

// StaticOptions configures a static site build.
type StaticOptions struct {
	BuildImage string // builder image, used only with Command
	Command    string // e.g. "npm run build"; empty serves files as-is
	OutputDir  string // relative directory with the built site, e.g. "dist"
	SPA        bool   // serve index.html for unknown paths
}

// nginxConf is the server config for static sites: no directory listings,
// no dotfiles (except .well-known), cache headers for assets and basic
// security headers. It contains no single quotes so it can be written with
// printf in a RUN instruction.
func nginxConf(spa bool) string {
	fallback := "=404"
	if spa {
		fallback = "/index.html"
	}
	return strings.Join([]string{
		"server {",
		"  listen 80;",
		"  server_name _;",
		"  root /usr/share/nginx/html;",
		"  index index.html index.htm;",
		"  server_tokens off;",
		"  autoindex off;",
		"  add_header X-Content-Type-Options nosniff always;",
		"  add_header Referrer-Policy strict-origin-when-cross-origin always;",
		"  location ~ /\\.(?!well-known/) { deny all; return 404; }",
		"  location ~* \\.(?:css|js|mjs|woff2?|ttf|otf|eot|svg|png|jpe?g|gif|webp|avif|ico)$ {",
		"    expires 7d;",
		"    add_header Cache-Control public;",
		"    add_header X-Content-Type-Options nosniff always;",
		"    try_files $uri =404;",
		"  }",
		"  location / { try_files $uri $uri/ $uri.html " + fallback + "; }",
		"  gzip on;",
		"  gzip_types text/plain text/css application/javascript application/json image/svg+xml;",
		"}",
		"",
	}, "\n")
}

// shellQuote single-quotes s for /bin/sh.
func shellQuote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}

// StaticDockerfile renders the Dockerfile for a static site.
func StaticDockerfile(o StaticOptions) (string, error) {
	out, err := CleanRelPath(o.OutputDir)
	if err != nil {
		return "", fmt.Errorf("output directory: %w", err)
	}
	var b strings.Builder
	b.WriteString("# Generated by SimplePanel for a static site.\n")
	if strings.TrimSpace(o.Command) != "" {
		img := orDefault(o.BuildImage, DefaultStaticBuildImage)
		if err := ValidImage(img); err != nil {
			return "", fmt.Errorf("build image: %w", err)
		}
		fmt.Fprintf(&b, "FROM %s AS build\nWORKDIR /src\nCOPY . .\n", img)
		// Install Node dependencies when the project has a package.json and
		// the builder has npm; other builders (Hugo, etc.) skip this.
		b.WriteString(`RUN if [ -f package.json ] && command -v npm >/dev/null 2>&1; then ` +
			`if [ -f pnpm-lock.yaml ]; then corepack enable && pnpm install --frozen-lockfile; ` +
			`elif [ -f yarn.lock ]; then corepack enable && yarn install --frozen-lockfile; ` +
			`elif [ -f package-lock.json ]; then npm ci; ` +
			`else npm install; fi; fi` + "\n")
		cmd, _ := json.Marshal([]string{"/bin/sh", "-c", o.Command})
		fmt.Fprintf(&b, "RUN %s\n", cmd)
	} else {
		b.WriteString("FROM alpine:3.22 AS build\nWORKDIR /src\nCOPY . .\n")
	}
	src := "/src"
	if out != "" {
		src += "/" + out
	}
	fmt.Fprintf(&b, "RUN test -d %s || { echo %s; exit 1; }\n", shellQuote(src),
		shellQuote("Output directory "+orDefault(out, ".")+" was not found after the build"))
	fmt.Fprintf(&b, "RUN rm -rf %s %s\n", shellQuote(src+"/"+staticDockerfile), shellQuote(src+"/.git"))
	fmt.Fprintf(&b, "\nFROM %s\n", StaticServerImage)
	// Exec form keeps the multi-line config on one Dockerfile line (JSON
	// escapes the newlines) and avoids variable substitution of $uri.
	conf, _ := json.Marshal([]string{"/bin/sh", "-c",
		"rm -rf /usr/share/nginx/html/* && printf '%s' " + shellQuote(nginxConf(o.SPA)) + " > /etc/nginx/conf.d/default.conf"})
	fmt.Fprintf(&b, "RUN %s\n", conf)
	fmt.Fprintf(&b, "COPY --from=build %s/ /usr/share/nginx/html/\n", src)
	b.WriteString("EXPOSE 80\n")
	return b.String(), nil
}

// ResolveBuildType decides how to build a cloned repository: "dockerfile"
// or "static". In auto mode a Dockerfile wins when present.
func ResolveBuildType(buildType, ctxDir, dockerfile string) string {
	switch buildType {
	case "dockerfile", "static":
		return buildType
	}
	if fi, err := os.Lstat(filepath.Join(ctxDir, filepath.FromSlash(orDefault(dockerfile, "Dockerfile")))); err == nil && fi.Mode().IsRegular() {
		return "dockerfile"
	}
	return "static"
}

// WriteStaticDockerfile renders and writes the generated Dockerfile into the
// build context and returns its name relative to the context.
func WriteStaticDockerfile(ctxDir string, o StaticOptions) (string, string, error) {
	df, err := StaticDockerfile(o)
	if err != nil {
		return "", "", err
	}
	if err := os.WriteFile(filepath.Join(ctxDir, staticDockerfile), []byte(df), 0o644); err != nil {
		return "", "", err
	}
	return staticDockerfile, df, nil
}
